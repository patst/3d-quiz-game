/**
 * Curriculum source documents (docs/curriculum/sources/).
 *
 *   npm run curriculum:sources            regenerate text/ and README checksums from pdf/
 *   npm run curriculum:sources -- --fetch re-download every PDF from its URL first
 *
 * After `--fetch`, `git diff docs/curriculum/sources/text` shows what the ministry changed.
 * Needs `curl` and `pdftotext` (poppler-utils) on the PATH. Build-time tool only; the game
 * never makes network calls (ADR-0004).
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

interface Source {
  id: string;
  title: string;
  status: string;
  url: string;
  page?: string;
  retrieved: string;
}

const DIR = 'docs/curriculum/sources';
const MANIFEST = join(DIR, 'sources.json');
const fetchAll = process.argv.includes('--fetch');
const today = new Date().toISOString().slice(0, 10);

const sources = JSON.parse(readFileSync(MANIFEST, 'utf8')) as Source[];
mkdirSync(join(DIR, 'pdf'), { recursive: true });
mkdirSync(join(DIR, 'text'), { recursive: true });

const rows: string[] = [];
for (const src of sources) {
  const pdf = join(DIR, 'pdf', `${src.id}.pdf`);
  const txt = join(DIR, 'text', `${src.id}.txt`);
  if (fetchAll) {
    console.log(`fetch ${src.id}`);
    execFileSync('curl', ['-sSfL', '--retry', '3', '-o', pdf, src.url], { stdio: 'inherit' });
    src.retrieved = today;
  }
  if (!existsSync(pdf)) throw new Error(`Missing ${pdf} — run with --fetch`);
  // -layout keeps the two-column competence tables readable; -q hides font warnings.
  execFileSync('pdftotext', ['-layout', '-q', pdf, txt]);
  // Drop trailing spaces so diffs only show real text changes.
  writeFileSync(txt, readFileSync(txt, 'utf8').replace(/[ \t]+$/gm, ''));
  const bytes = readFileSync(pdf);
  const sha = createHash('sha256').update(bytes).digest('hex').slice(0, 16);
  const kb = Math.round(bytes.length / 1024);
  rows.push(
    `| \`${src.id}\` | [${src.title}](${src.url}) | ${src.status} | ${src.retrieved} | ${kb} KB | \`${sha}\` |`,
  );
}

writeFileSync(MANIFEST, `${JSON.stringify(sources, null, 2)}\n`);

const readme = `# Curriculum source documents

Copies of the official documents behind \`../niedersachsen.md\`. They are stored so that a
later update can be **diffed** against the version we based our content on.

- \`pdf/<id>.pdf\`: the original file, unchanged. Copyright stays with the Niedersächsisches
  Kultusministerium. We keep it here only as a research reference.
- \`text/<id>.txt\`: \`pdftotext -layout\` output, for readable diffs.
- \`sources.json\`: the manifest (id, title, status, original URL, retrieval date).

**Updating:** run \`npm run curriculum:sources -- --fetch\`. It needs \`curl\` and
\`pdftotext\`. Then run \`git diff docs/curriculum/sources/text\`, adjust
\`niedersachsen.md\` and the competency catalogue, and commit everything together.
When a new edition gets a new URL (for example, a draft becomes final), add a new entry
instead of overwriting the old one, so both editions stay comparable.

<!-- generated by scripts/curriculum-sources.ts — edit sources.json, not this table -->
| id | document (original URL) | status | retrieved | size | sha256 (16) |
|---|---|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync(join(DIR, 'README.md'), readme);
console.log(`${sources.length} sources → ${DIR}`);
